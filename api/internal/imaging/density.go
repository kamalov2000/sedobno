// Признаки «плотной мелкой этикетки» — то, что сервер может посчитать по кадру ДО
// вызова модели, без OCR и без единого токена.
//
// Зачем: на этикетках с мелким плотным шрифтом дешёвая модель не читает текст, а
// СОЧИНЯЕТ правдоподобный состав «типового продукта категории» — причём сочиняет и
// transcription тоже, согласованно, так что антигаллюцинационный гейт (сверяющий одно
// с другим) слеп по конструкции. Живой кейс: онигири «Снежный краб», четыре прогона
// одного файла — 81/38/68/74, верен только эскалированный на Sonnet (38).
//
// Метрика ловит ровно то, что ломает чтение: детали, ИСЧЕЗАЮЩИЕ при ужатии. Крупные
// буквы переживают уменьшение вдвое, мелкие — нет. На корпусе из 21 этикетки + онигири
// последний оказался первым с большим отрывом (0.544 против 0.346 у следующей).

// Density — измеримые характеристики кадра. Оба числа безразмерные, 0..1.
type Density struct {
	// EdgeFrac — доля пикселей с сильным градиентом: сколько в кадре вообще
	// контуров (текста, границ, фактуры). Сам по себе слабый признак — плотный
	// текст и пёстрая фактура дают близкие значения.
	EdgeFrac float64
	// FineLoss — какая часть краевой энергии теряется при повторном ужатии вдвое.
	// Это и есть «мелкий шрифт на грани читаемости»: 0 — в кадре нет деталей,
	// которые ломает масштабирование; 0.5+ — половина контуров живёт на пределе
	// разрешения.
	FineLoss float64
}

// edgeThreshold — порог «сильного градиента» в единицах яркости 0..255. Подобран
// так, чтобы не считать краем шум JPEG-компрессии (качество 85) и мягкие тени.
const edgeThreshold = 24.0

// ForceEscalateFineLoss — порог форс-эскалации ПО УМОЛЧАНИЮ (переопределяется
// SCAN_FORCE_ESCALATE_FINE_LOSS без пересборки).
//
// ВАЖНО о шкале: числа этой реализации НЕ совпадают с числами прототипа на Python,
// по которому порог выбирался. Здесь ресайз идёт CatmullRom (тем же, что и Normalize)
// по уже пережатому JPEG q85, и обе разницы поднимают fine_loss примерно на 0.15–0.25.
// Порядок кадров сохраняется, абсолютные значения — нет. Сравнивать замеры между
// реализациями нельзя; калибровать порог можно ТОЛЬКО по числам из телеметрии.
//
// На шкале этой реализации 0.40 накрывает ОБА известных случая сочинённого состава:
// онигири «Снежный краб» (0.69) и «Слон в чайном лесу» (0.44) — оба лежат в
// testdata/_beta_findings. Срабатывает на ~12% кадров корпуса (3 из 25).
// Корпус мал и однороден (половина — одна фотосессия), поэтому это оценка порядка
// величины, а не измеренная частота; ради перекалибровки fine_loss пишется в
// телеметрию на КАЖДОМ скане, а не только на сработавших.
const ForceEscalateFineLoss = 0.40

// Measure считает признаки по УЖЕ НОРМАЛИЗОВАННОМУ кадру (выход Normalize: ≤1500px,
// JPEG). Именно по нормализованному, а не по исходнику: в модель уходит он, и
// «мелко ли для модели» определяется тем, что осталось после ресайза, а не тем, что
// было в оригинале.
//
// Ошибку декодирования не считаем фатальной для скана — вызывающий трактует её как
// «признак недоступен» и работает как раньше.
func Measure(jpegData []byte) (Density, error) {
	img, _, err := image.Decode(bytes.NewReader(jpegData))
	if err != nil {
		return Density{}, ErrDecode
	}
	gray, w, h := toGray(img)
	if w < 4 || h < 4 {
		return Density{}, nil // кадр вырожденный: мерить нечего, признака нет
	}

	full := edgeFraction(gray, w, h)
	if full == 0 {
		return Density{}, nil // ровная заливка — деталей нет вовсе
	}

	// Половинный проход: ужимаем вдвое и растягиваем обратно к исходному размеру.
	// Растягивание обязательно — сравнивать доли краёв можно только при одинаковом
	// знаменателе; иначе разница считалась бы между разными сетками пикселей.
	halved := edgeFraction(downUp(gray, w, h), w, h)

	loss := (full - halved) / full
	if loss < 0 {
		loss = 0 // ужатие добавило краёв (артефакты интерполяции) — не «мелкий шрифт»
	}
	return Density{EdgeFrac: full, FineLoss: loss}, nil
}

// toGray переводит кадр в 8-битную яркость по ITU-R 601-2 (та же формула, что у
// PIL .convert("L"), — чтобы пороги, откалиброванные на корпусе, значили то же самое).
func toGray(img image.Image) ([]float64, int, int) {
	b := img.Bounds()
	w, h := b.Dx(), b.Dy()
	out := make([]float64, w*h)
	for y := 0; y < h; y++ {
		for x := 0; x < w; x++ {
			r, g, bl, _ := img.At(b.Min.X+x, b.Min.Y+y).RGBA()
			// RGBA() отдаёт 16-битные каналы — приводим к 0..255.
			out[y*w+x] = 0.299*float64(r>>8) + 0.587*float64(g>>8) + 0.114*float64(bl>>8)
		}
	}
	return out, w, h
}

// edgeFraction — доля пикселей, где модуль градиента выше порога. Градиент —
// разности вперёд по обеим осям на сетке (w-1)×(h-1).
func edgeFraction(a []float64, w, h int) float64 {
	if w < 2 || h < 2 {
		return 0
	}
	var over int
	total := (w - 1) * (h - 1)
	for y := 0; y < h-1; y++ {
		row := y * w
		next := row + w
		for x := 0; x < w-1; x++ {
			gx := a[row+x+1] - a[row+x]
			gy := a[next+x] - a[row+x]
			if math.Hypot(gx, gy) > edgeThreshold {
				over++
			}
		}
	}
	return float64(over) / float64(total)
}

// downUp ужимает яркостную карту вдвое и растягивает обратно. Работает через
// image.Gray и тот же CatmullRom, которым ресайзит Normalize, — чтобы измерялась
// потеря деталей на РЕАЛЬНОМ конвейере проекта, а не на абстрактном фильтре.
func downUp(a []float64, w, h int) []float64 {
	src := image.NewGray(image.Rect(0, 0, w, h))
	for i, v := range a {
		src.Pix[i] = clamp8(v)
	}
	hw, hh := w/2, h/2
	if hw < 1 {
		hw = 1
	}
	if hh < 1 {
		hh = 1
	}
	small := image.NewGray(image.Rect(0, 0, hw, hh))
	draw.CatmullRom.Scale(small, small.Bounds(), src, src.Bounds(), draw.Over, nil)
	back := image.NewGray(image.Rect(0, 0, w, h))
	draw.CatmullRom.Scale(back, back.Bounds(), small, small.Bounds(), draw.Over, nil)

	out := make([]float64, w*h)
	for i, p := range back.Pix {
		if i >= len(out) {
			break
		}
		out[i] = float64(p)
	}
	return out
}

func clamp8(v float64) uint8 {
	switch {
	case v <= 0:
		return 0
	case v >= 255:
		return 255
	default:
		return uint8(v + 0.5)
	}
}
