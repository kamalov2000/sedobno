package meal

import (
	"strings"

	"github.com/sostav/api/internal/llm"
)

// Алкоголь в согласовании калорийности. Формула Атуотера (4Б+4У+9Ж) не видит этанола:
// он не белок, не жир и не углевод, но даёт 7 ккал на грамм. Пока сервер сверял ккал
// блюда только по макросам, любой алкоголь схлопывался в свои углеводы — живой разбор
// 24.08.2026 показал бокал сухого красного как 17 ккал вместо ~170 (модель отдала 144,
// сервер переписал их в 4·4,6 г углеводов). Это не про вино: так же ложились пиво,
// крепкое, коктейли и ликёры.
//
// Чинится в два хода. Основной — поле alcohol_g в схеме разбора: модель оценивает граммы
// чистого спирта по типу напитка и объёму, а сервер добавляет 7·alcohol_g в формулу.
// Страховочный — skipAlcoholRecalc: если alcohol_g не пришло (старая запись в базе,
// правка с клиента, сбой модели), а позиция явно алкогольная, пересчёт не применяется
// вовсе. Молчаливое занижение в разы хуже, чем отсутствие коррекции.

// skipAlcoholRecalc — согласование ккал для этого блюда применять НЕЛЬЗЯ: спиртное без
// заявленного alcohol_g. Считать его по одним макросам — гарантированно занизить.
func skipAlcoholRecalc(d llm.MealItem) bool {
	return d.AlcoholG == 0 && looksAlcoholic(d.Name)
}

// alcoholExactWords — слова, которые считаем алкоголем ТОЛЬКО при точном совпадении.
// Короткие корни ловят посторонние слова: «ром» живёт в «ромашковом чае» и «ромштексе»,
// «эль» — в «эльзасском», «вино» — в «винограде».
var alcoholExactWords = map[string]bool{
	"вино": true, "вина": true, "вине": true, "вином": true, "вин": true,
	"ром": true, "рома": true, "ромом": true, "роме": true,
	"джин": true, "джина": true, "джином": true,
	"эль": true, "эля": true, "элем": true,
	"саке": true, "брага": true, "браги": true, "бражка": true,
}

// alcoholStems — начала слов: сравниваем ПОСЛОВНО, не подстрокой. Подстрочный поиск
// принял бы «полоВИНАу» и «ВИНегрет» за спиртное, а «пиво» — за «пивную кружку».
var alcoholStems = []string{
	"винишк", "винцо",
	"пиво", "пива", "пиве", "пивом", "пивк", "пивас",
	"водк", "водочк", "виски", "коньяк", "коньячн",
	"текил", "бренди", "абсент", "самогон", "чача", "чачи", "граппа", "кальвадос",
	"шампанск", "игрист", "просекк", "просек", "портвейн", "херес", "мадер", "вермут",
	"сидр", "лагер", "портер", "стаут",
	"глинтвейн", "грог", "пунш", "сангри", "мохито", "дайкири", "мартини", "маргарит",
	"ликер", "наливк", "настойк", "медовух", "соджу", "кампари", "апероль", "шнапс",
	"спиртн", "алкогольн",
}

// nonAlcoholMarkers — метки безалкогольного варианта: встретились в названии — блюдо
// алкогольным не считаем, чем бы оно ни называлось. Безалкогольное пиво — обычный
// напиток, и обычное согласование ккал ему нужно.
var nonAlcoholMarkers = []string{"безалкогол", "без алкогол", "б/а ", "0%", "0 %", "детское шампанское"}

// looksAlcoholic — название позиции явно про спиртное. Это ТОЛЬКО страховка на случай
// отсутствия alcohol_g; полнота списка здесь не критична — цена промаха асимметрична:
// пропущенный напиток теряет коррекцию, лишний просто остаётся с числом модели.
func looksAlcoholic(name string) bool {
	n := strings.ToLower(strings.ReplaceAll(strings.TrimSpace(name), "ё", "е"))
	for _, m := range nonAlcoholMarkers {
		if strings.Contains(n, m) {
			return false
		}
	}
	for _, w := range strings.FieldsFunc(n, func(r rune) bool {
		return !('а' <= r && r <= 'я' || 'a' <= r && r <= 'z' || '0' <= r && r <= '9')
	}) {
		if alcoholExactWords[w] {
			return true
		}
		for _, stem := range alcoholStems {
			if strings.HasPrefix(w, stem) {
				return true
			}
		}
	}
	return false
}
