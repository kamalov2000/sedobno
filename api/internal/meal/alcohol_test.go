// Согласование ккал у алкоголя: этанол (7 ккал/г) — полноправное слагаемое формулы.
// Без него сервер переписывал спиртное в его углеводы: бокал сухого красного, который
// модель оценила в 144 ккал, доезжал до пользователя как 17 (живой разбор 24.08.2026).
//
// Числа alcohol_g в таблице — по формуле промпта: (мл) × (крепость) × 0.789.
func TestSanitizeDishes_АлкогольНеЗанижается(t *testing.T) {
	tests := []struct {
		name string
		dish llm.MealItem
		want float64 // ожидаемая ккал позиции после санитизации
	}{
		{
			// 200 мл × 13% × 0.789 ≈ 20.5 г спирта. computed = 4·0.2 + 4·5.2 + 7·20.5 ≈ 165,
			// модель дала 170 — расхождение 3%, в допуске: число модели остаётся.
			name: "красное сухое 200 мл",
			dish: llm.MealItem{Name: "вино красное сухое", Grams: 200, Kcal: 170,
				ProteinG: 0.2, FatG: 0, CarbG: 5.2, AlcoholG: 20.5},
			want: 170,
		},
		{
			// 500 мл × 5% × 0.789 ≈ 19.7 г. computed = 4·18 + 7·19.7 ≈ 210 против 215 — в допуске.
			name: "пиво светлое 500 мл",
			dish: llm.MealItem{Name: "пиво светлое", Grams: 500, Kcal: 215,
				ProteinG: 0, FatG: 0, CarbG: 18, AlcoholG: 19.7},
			want: 215,
		},
		{
			// 50 мл × 40% × 0.789 ≈ 15.8 г, углеводов нет. computed = 7·15.8 ≈ 110.6 против 110.
			name: "водка 50 мл",
			dish: llm.MealItem{Name: "водка", Grams: 50, Kcal: 110, AlcoholG: 15.8},
			want: 110,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := sanitizeDishes([]llm.MealItem{tt.dish})
			if len(got) != 1 {
				t.Fatalf("блюд на выходе %d, ждали 1", len(got))
			}
			if math.Abs(got[0].Kcal-tt.want) > 1 {
				t.Errorf("kcal=%v, ждали ~%v", got[0].Kcal, tt.want)
			}
			// Прежняя формула без спирта дала бы вот столько — проверяем, что мы НЕ там.
			if atwater := 4*tt.dish.ProteinG + 4*tt.dish.CarbG + 9*tt.dish.FatG; got[0].Kcal == atwater {
				t.Errorf("kcal схлопнулась в 4Б+4У+9Ж (%v) — этанол не учтён", atwater)
			}
			if got[0].AlcoholG != round1(tt.dish.AlcoholG) {
				t.Errorf("alcohol_g=%v, ждали %v (поле должно пережить санитизацию)",
					got[0].AlcoholG, tt.dish.AlcoholG)
			}
		})
	}
}

// Неалкогольный путь не тронут: расхождение с 4Б+4У+9Ж по-прежнему чинится пересчётом,
// согласованные числа по-прежнему остаются как есть. Это важнее самих алкогольных случаев —
// оно доказывает, что правка не изменила поведение для всех остальных блюд.
func TestSanitizeDishes_БезАлкоголяПоведениеПрежнее(t *testing.T) {
	tests := []struct {
		name string
		dish llm.MealItem
		want float64
	}{
		{
			// 4·35 = 140, модель дала 139 — в допуске, оставляем.
			name: "кола 330 мл, числа согласованы",
			dish: llm.MealItem{Name: "кола", Grams: 330, Kcal: 139, CarbG: 35},
			want: 139,
		},
		{
			// Та же кола с абсурдной ккал: пересчёт из макросов работает как раньше.
			name: "кола 330 мл, ккал врёт",
			dish: llm.MealItem{Name: "кола", Grams: 330, Kcal: 10, CarbG: 35},
			want: 140,
		},
		{
			// 4·31 + 9·3.6 = 156.4, модель дала 165 — расхождение 5%, в допуске.
			name: "куриная грудка 150 г",
			dish: llm.MealItem{Name: "куриная грудка отварная", Grams: 150, Kcal: 165,
				ProteinG: 31, FatG: 3.6, CarbG: 0},
			want: 165,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := sanitizeDishes([]llm.MealItem{tt.dish})
			if len(got) != 1 {
				t.Fatalf("блюд на выходе %d, ждали 1", len(got))
			}
			if math.Abs(got[0].Kcal-tt.want) > 0.5 {
				t.Errorf("kcal=%v, ждали %v", got[0].Kcal, tt.want)
			}
			if got[0].AlcoholG != 0 {
				t.Errorf("alcohol_g=%v у неалкогольного блюда", got[0].AlcoholG)
			}
		})
	}
}

// Страховка: alcohol_g не пришло (старая запись, правка с клиента, сбой модели), а позиция
// явно алкогольная — пересчёт не применяем вовсе. Молчаливое занижение в разы хуже, чем
// отсутствие коррекции: пользователь увидит хотя бы оценку модели, а не 17 ккал за бокал.
func TestSanitizeDishes_АлкогольБезПоляНеПересчитывается(t *testing.T) {
	// Ровно то, что вернула модель 24.08.2026, но без alcohol_g.
	got := sanitizeDishes([]llm.MealItem{
		{Name: "красное вино", Grams: 200, Kcal: 144, ProteinG: 0.2, FatG: 0, CarbG: 4.6},
	})
	if len(got) != 1 {
		t.Fatalf("блюд на выходе %d, ждали 1", len(got))
	}
	if got[0].Kcal != 144 {
		t.Errorf("kcal=%v, ждали 144 (число модели без изменений); 19.2 — это старый дефект", got[0].Kcal)
	}
}

// А вот ккал=0 у алкоголя пересчитывать всё равно нечем — но и молчать нельзя: блюдо
// уходит на проверку пользователю (санити нулевой плотности), а не тонет с нулём.
func TestSanitizeDishes_АлкогольСНулевойКкалНаПроверку(t *testing.T) {
	got := sanitizeDishes([]llm.MealItem{
		{Name: "виски", Grams: 50, Kcal: 0, Confidence: 0.9},
	})
	if len(got) != 1 {
		t.Fatalf("блюд на выходе %d, ждали 1", len(got))
	}
	if !got[0].NeedsReview {
		t.Errorf("needs_review=false — нулевая ккал у алкоголя должна уходить на проверку")
	}
}

func TestLooksAlcoholic(t *testing.T) {
	yes := []string{
		"вино красное сухое", "бокал вина", "красное вино", "вином закусили",
		"пиво светлое", "пивко", "водка", "рюмка водки", "виски", "коньяк",
		"шампанское брют", "игристое", "просекко", "сидр яблочный", "джин-тоник",
		"ром", "текила", "ликер бейлиз", "ликёр", "глинтвейн", "мохито", "мартини",
		"наливка вишнёвая", "самогон", "портвейн", "вермут", "саке", "эль тёмный",
	}
	for _, n := range yes {
		if !looksAlcoholic(n) {
			t.Errorf("looksAlcoholic(%q)=false, ждали true", n)
		}
	}
	// Ложные срабатывания дороже пропуска: на них мы отключаем коррекцию у обычной еды.
	// «Половина», «винегрет», «виноград», «ромашковый» — те самые слова, на которых
	// подстрочный поиск («вина», «вин», «ром») ломается.
	no := []string{
		"винегрет", "виноград", "виноградный сок", "половина авокадо", "половинка банана",
		"ромашковый чай", "ромштекс", "квас", "кефир", "безалкогольное пиво",
		"пиво безалкогольное 0%", "детское шампанское", "куриная грудка", "борщ",
		"винный уксус в салате" /* соус, а не напиток: спирта в нём нет */, "эльзасский пирог",
	}
	for _, n := range no {
		if looksAlcoholic(n) {
			t.Errorf("looksAlcoholic(%q)=true, ждали false", n)
		}
	}
}
