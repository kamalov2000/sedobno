package meal

import (
	"strings"

	"github.com/sostav/api/internal/llm"
)

// Эскалация разбора еды на сильную модель по РИСКОВОМУ ИМЕНИ блюда.
//
// Почему по имени, а не по confidence или числу блюд (см. диагностику 2026-07-21):
//   - confidence не разделяет: у Haiku самая грубая ошибка (кимчи→бекон) несёт МАКСИМАЛЬНЫЙ
//     confidence 0.88 — разделяющего порога не существует;
//   - двойной проход не ловит: Haiku при temperature=0 детерминирован, систематическая
//     ошибка стабильна между проходами (оба раза «бекон»);
//   - число блюд не коррелирует: простейший холодник (1 блюдо) ошибочен, составной салат
//     (4 блюда) верен.
//
// Рабочий сигнал — сам КЛАСС, который вернул Haiku: модель по визуальному прайору
// сваливает неоднозначное в частотный класс (белое мясо кусочками → «креветки», красная
// ферментированная капуста → «бекон»). Если Haiku вернул рисковый класс — перепроверяем
// на Sonnet, который эти классы различает.
//
// Список СТАРТОВЫЙ и заведомо неполный — он не обязан быть точным, его задача поднять
// метрику: admin/stats покажет, на каких классах срабатывает эскалация и ловит ли она
// реальные ошибки (правит ли юзер эскалированные приёмы реже). По этим данным список
// сужается/расширяется. Ложное срабатывание здесь дёшево (лишний вызов Sonnet на реальных
// креветках — они и правда креветки, Sonnet подтвердит), пропуск — дорого (ошибка уедет
// в дневник), поэтому список смещён в сторону полноты.
//
// Подстроки в нижнем регистре: сопоставление — по вхождению в нормализованное имя блюда.
// Осознанно НЕ включены слишком общие слова («нарезка» — бывает овощная, «рыба» — обычно
// верна): они дали бы шквал ложных эскалаций без сигнала.
var riskyDishSubstrings = []string{
	// Морепродукты — куда сваливается белое/розоватое мясо кусочками (курица→креветки).
	"креветк", "морепродукт", "кальмар", "мидии", "устриц", "краб", "гребешк", "лангустин",
	// Мясная нарезка / бекон — куда сваливается красное/полосатое/ферментированное (кимчи→бекон).
	"бекон", "прошутто", "хамон", "ветчин", "салями", "пепперони", "бастурма", "карпаччо",
	"мясная нарезка", "мясной деликатес",
}

// riskyDishName нормализует имя и возвращает первую рисковую подстроку, если имя блюда
// относится к рисковому классу. Пусто — имя не рисковое.
func riskyDishName(name string) string {
	n := strings.ToLower(strings.TrimSpace(name))
	if n == "" {
		return ""
	}
	for _, sub := range riskyDishSubstrings {
		if strings.Contains(n, sub) {
			return sub
		}
	}
	return ""
}

// firstRiskyName возвращает первое рисковое имя среди блюд (в порядке dishes) — этим
// именем и помечается эскалация в метрике. Пусто — рискового класса в наборе нет.
func firstRiskyName[T any](dishes []T, nameOf func(T) string) string {
	for _, d := range dishes {
		if r := riskyDishName(nameOf(d)); r != "" {
			return r
		}
	}
	return ""
}

// --- Второй триггер: яичное блюдо, названное фруктом ---
//
// Растёкшийся жёлто-оранжевый желток на белке модели принимают за жёлтый фрукт, и его
// калории приплюсовываются к настоящим. Ошибка воспроизводима и НЕ лечится промптом у
// младшей модели: на живом кадре с глазуньей и гречкой Haiku дал «яйца пашот с апельсином
// и миндалём», Sonnet — «яйца пашот с манго и кунжутом» (05.08.2026). После правила в
// meal_v1.txt Sonnet стал отвечать верно («яичница (глазунья)»), а Haiku продолжил
// добавлять апельсин даже при прямом запрете.
//
// Отсюда узкий триггер: блюдо, где ОДНОВРЕМЕННО есть яичные примитивы (yolk/white — то
// есть модель яйца увидела) и фруктовое слово в названии. Сочетание «яичница с апельсином»
// на одной тарелке редкое, а вот желток, названный фруктом, — частое.
//
// Ложное срабатывание дёшево и безвредно: если на тарелке РЕАЛЬНО лежат дольки апельсина
// рядом с яичницей, Sonnet с новым правилом подтвердит их по кожуре и сегментам долек —
// мы просто заплатим ~1.3 ₽ за проверку. Пропуск дороже: неверные калории уедут в дневник.
var yolkFruitSubstrings = []string{
	"апельсин", "мандарин", "манго", "персик", "нектарин", "абрикос",
	"хурма", "хурмы", "грейпфрут", "айва", "дыня", "дыни", "тыкв",
}

// hasEggPieces — модель вынесла в примитивы желток или белок, то есть яйца на фото увидела.
func hasEggPieces(pieces []llm.MealPiece) bool {
	for _, p := range pieces {
		if p.Count > 0 && isEggPieceKind(p.Kind) {
			return true
		}
	}
	return false
}

// eggFruitTrigger возвращает описание триггера, если хоть одно блюдо одновременно яичное
// и названо фруктом. Пусто — такого сочетания нет.
func eggFruitTrigger(dishes []llm.MealItem) string {
	for _, d := range dishes {
		if !hasEggPieces(d.Pieces) {
			continue
		}
		n := strings.ToLower(strings.TrimSpace(d.Name))
		for _, fruit := range yolkFruitSubstrings {
			if strings.Contains(n, fruit) {
				return "яйцо+" + fruit
			}
		}
	}
	return ""
}
