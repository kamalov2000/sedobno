package meal

import (
	"strings"

	"github.com/sostav/api/internal/llm"
)

// Жир, который уже посчитан в самом блюде.
//
// Ложечные добавки (масло, сливочное) — догадка о невидимом: «кашу обычно заправляют»,
// «жарили на масле». Догадка законна ровно до тех пор, пока этого жира НЕТ в базовой
// оценке. У части блюд он там есть по определению названия:
//
//   - жареная картошка оценивается в ~173 ккал/100 г против 80 у варёной, и разница —
//     это и есть масло жарки. Две ложки сверху давали 350 ккал на 150 г вместо ~260;
//   - круассан — 431 ккал/100 г, столько он весит ВМЕСТЕ со сливочным маслом теста;
//     предположенная ложка добавляла ещё 37.
//
// Промпт об этом просит, но просьба — не гарантия: 09.09.2026 одна и та же «жареная
// картошка» в двух прогонах подряд пришла сначала без ложек, потом с двумя. Поэтому
// правило продублировано детерминированно на сервере, по названию блюда.
//
// Снимаются ТОЛЬКО предположенные добавки. Названное человеком («картошка с маслом»)
// остаётся всегда: там жир — факт, а не догадка, и молча вычитать его нельзя.

// fryMarkers — блюдо приготовлено в жире, и типовая калорийность это уже учитывает.
var fryMarkers = []string{
	"жарен", "обжарен", "зажарен", "поджарен", "фри", "фритюр", "во фритюре",
	"на сковород", "гриль", "на масле",
}

// bakedMarkers — выпечка и готовые изделия: жир входит в рецепт теста.
var bakedMarkers = []string{
	"круассан", "слойк", "слоён", "печень", "кекс", "торт", "пирожн", "пирожок",
	"булочк", "булка", "ватрушк", "вафл", "маффин", "кексик", "пончик", "чебурек",
	"беляш", "хачапури", "штрудел", "эклер", "круасан",
}

// fatAlreadyInBase — по названию видно, что жир входит в саму оценку блюда.
func fatAlreadyInBase(name string) bool {
	n := strings.ToLower(strings.TrimSpace(name))
	for _, m := range fryMarkers {
		if strings.Contains(n, m) {
			return true
		}
	}
	for _, m := range bakedMarkers {
		if strings.Contains(n, m) {
			return true
		}
	}
	return false
}

// isSpoonFat — ложечная добавка жира (масло растительное или сливочное). Сахар сюда не
// относится: он не жир, и к вопросу о двойном счёте жира отношения не имеет.
func isSpoonFat(kind string) bool { return kind == kindOilVeg || kind == kindButter }

// dropRedundantFat снимает ПРЕДПОЛОЖЕННЫЙ жир у блюда, где он уже в базовой оценке.
// Названные и увиденные добавки не трогает.
func dropRedundantFat(d llm.MealItem) llm.MealItem {
	if len(d.Pieces) == 0 || !fatAlreadyInBase(d.Name) {
		return d
	}
	out := make([]llm.MealPiece, 0, len(d.Pieces))
	for _, p := range d.Pieces {
		if p.Assumed && isSpoonFat(p.Kind) {
			continue // этот жир уже посчитан в самом блюде
		}
		out = append(out, p)
	}
	if len(out) == 0 {
		out = nil
	}
	d.Pieces = out
	return d
}
