package meal

import "strings"

// Санитайзинг ремарки модели (note). Поле уходит человеку в интерфейс как есть, и модель
// нет-нет да и вытащит в него наш внутренний словарь: живой разбор 08.09 отдал
// «Яйца разложены на желток/белок (по 3 шт), масса и КБЖУ считаются сервером по pieces» —
// фраза, в которой для пользователя бессмысленны и «сервер», и «pieces».
//
// Промпт теперь это запрещает, но промпт — просьба, а не гарантия. Здесь гарантия:
// ремарку с внутренними терминами НЕ показываем вовсе. Пустой note — штатный случай
// (интерфейс просто не рисует блок), а протёкший контракт в тексте — стыдно и непонятно.
//
// Режем целиком, а не вырезаем слова: обрубок вроде «Яйца разложены на желток/белок (по
// 3 шт), масса и КБЖУ считаются» читается ещё хуже оригинала.

// noteInternalTerms — слова, наличие которых означает, что модель заговорила о контракте,
// а не о еде. Проверяем в нижнем регистре, по вхождению.
var noteInternalTerms = []string{
	"pieces", "dish_kind", "yolk", "white", "protein_g", "fat_g", "carb_g", "grams",
	"kcal_per", "alcohol_g", "json", "схем", "поле ", "полей", "констант", "сервер",
	"бэкенд", "backend", "api",
}

// sanitizeNote возвращает ремарку, пригодную для показа человеку, либо "" — если модель
// протащила в неё внутренние термины.
func sanitizeNote(note string) string {
	n := strings.TrimSpace(note)
	if n == "" {
		return ""
	}
	low := strings.ToLower(n)
	for _, t := range noteInternalTerms {
		if strings.Contains(low, t) {
			return ""
		}
	}
	return n
}
