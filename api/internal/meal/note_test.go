package meal

import "testing"

// Ремарка уходит человеку в интерфейс. Живой случай 08.09: после правки количества
// желтков карточка показывала 2 желтка и 173 ккал, а под ней висело «Яйца разложены на
// желток/белок (по 3 шт), масса и КБЖУ считаются сервером по pieces» — и устаревшее, и
// написанное не для людей. Числа чинит фронт (подпись «первоначальная оценка»), словарь —
// здесь.
func TestSanitizeNote(t *testing.T) {
	// Протёкший контракт — не показываем вовсе: обрубок читался бы ещё хуже.
	leaked := []string{
		"Яйца разложены на желток/белок (по 3 шт), масса и КБЖУ считаются сервером по pieces",
		"Значения в поле grams приблизительные",
		"Масло вынесено в pieces",
		"Считает бэкенд по константам",
		"yolk и white посчитаны отдельно",
	}
	for _, n := range leaked {
		if got := sanitizeNote(n); got != "" {
			t.Errorf("ремарка с внутренним термином показана человеку: %q → %q", n, got)
		}
	}

	// Нормальные ремарки — про еду и допущения — обязаны доезжать целиком.
	fine := []string{
		"Порция взята стандартная",
		"Соус оценён приблизительно, точный состав по фото не виден",
		"Крепость вина принята стандартной 12%",
		"Объём указан точно, калорийность по типовому сухому красному вину",
	}
	for _, n := range fine {
		if got := sanitizeNote(n); got != n {
			t.Errorf("нормальная ремарка потерялась: %q → %q", n, got)
		}
	}

	if got := sanitizeNote("   "); got != "" {
		t.Errorf("пробельная ремарка должна давать пустую строку, получили %q", got)
	}
}
