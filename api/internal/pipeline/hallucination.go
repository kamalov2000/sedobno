package pipeline

import (
	"log/slog"

	"github.com/sostav/api/internal/imaging"
	"github.com/sostav/api/internal/llm"
)

// Детекторы сочинённого состава — то, чего НЕ ловит transcription_gate.
//
// Гейт сверяет список ингредиентов с transcription ТОЙ ЖЕ модели. Когда модель не
// читает мелкий текст, а сочиняет состав «типового продукта категории», она сочиняет
// и переписку — согласованно. Гейт видит полное совпадение и молчит. Это не дыра в
// реализации, а предел конструкции: сверять ответ модели с её же ответом бесполезно,
// если врут обе половины сразу.
//
// Здесь два независимых от модели признака:
//
//	fine_loss (ДО вызова)  — в кадре много деталей, которые ломает масштабирование,
//	                         то есть шрифт на грани читаемости. Дешёвой модели такой
//	                         кадр не по зубам, и она уходит в выдумку.
//	позиций много,         — подпись подделки: сочиняя, модель выдаёт КОРОТКИЕ типовые
//	текста мало (ПОСЛЕ)      названия и много позиций, тогда как настоящая плотная
//	                         этикетка даёт длинные вложенные скобки. На онигири:
//	                         выдумки 11–12 позиций по 28–40 символов, правда — 6 позиций
//	                         по 192 символа.
//
// Первый признак доступен до вызова модели и потому даёт ФОРС-эскалацию: слабую
// модель на таком кадре не зовём вовсе. Второй считается по ответу и потому работает
// как обычная эскалация — после дешёвого прогона.

const (
	// suspectFineLoss — «кадр подозрительный, но не безнадёжный». Ниже порога
	// форс-эскалации: сам по себе на Sonnet не отправляет, но включает проверку
	// длины. Без этой связки детектор длины срабатывал бы на честных коротких
	// составах («мука, сахар, соль, дрожжи, вода» — пять позиций по 6 символов),
	// а это самая обычная этикетка, а не выдумка.
	suspectFineLoss = 0.25

	// minSuspectItems / maxCharsPerItem — форма подписи «много коротких позиций».
	// Пороги намеренно консервативны: цена ложной эскалации — лишние ~3.4 ₽, цена
	// пропуска — показанный пользователю выдуманный состав.
	minSuspectItems = 8
	maxCharsPerItem = 60
)

// Density — признаки кадра, посчитанные до вызова модели. Ноль означает «померить не
// удалось» (битый кадр): тогда ни один детектор не срабатывает и пайплайн ведёт себя
// ровно как раньше.
type frameDensity struct {
	EdgeFrac float64
	FineLoss float64
}

// measureFrames меряет набор кадров и возвращает МАКСИМУМ по fine_loss: состав может
// быть на одном-единственном плотном кадре, и разбавлять его средним по остальным
// («обзорное фото упаковки» + «крупный план состава») значило бы гасить сигнал.
// Ошибки замера не фатальны — кадр просто не вносит вклада.
func measureFrames(images []llm.Image, log *slog.Logger) frameDensity {
	var out frameDensity
	for _, img := range images {
		d, err := imaging.Measure(img.Data)
		if err != nil {
			if log != nil {
				log.Warn("замер плотности кадра не удался", "err", err)
			}
			continue
		}
		if d.FineLoss > out.FineLoss {
			out.FineLoss = d.FineLoss
		}
		if d.EdgeFrac > out.EdgeFrac {
			out.EdgeFrac = d.EdgeFrac
		}
	}
	return out
}

// CharsPerItem — средняя длина позиции состава в символах (рунах, не байтах: на
// кириллице байтовая длина вдвое больше и пороги поехали бы). Пустой список — 0.
func CharsPerItem(items []string) float64 {
	if len(items) == 0 {
		return 0
	}
	var total int
	for _, s := range items {
		total += len([]rune(s))
	}
	return float64(total) / float64(len(items))
}

// ShortItemsSuspicious — сработал ли детектор «позиций много, текста мало». Требует
// подозрительного кадра: на обычном фото короткие позиции — норма, а не признак лжи.
//
// Экспортирован, потому что тем же правилом сервер решает, стоит ли перепроверять
// СЛАБУЮ запись кэша (analysis_cache.go): там состав уже сохранён, и считать его
// форму заново дешевле, чем хранить рядом отдельный флаг.
func ShortItemsSuspicious(items []string, fineLoss float64) bool {
	if fineLoss < suspectFineLoss {
		return false
	}
	if len(items) < minSuspectItems {
		return false
	}
	return CharsPerItem(items) <= maxCharsPerItem
}
