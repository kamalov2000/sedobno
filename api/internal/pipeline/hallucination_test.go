// onigiriFineLoss — замеренная плотность того самого кадра (imaging.Measure на
// нормализованном фото). Выше и порога подозрения, и порога форс-эскалации.
const onigiriFineLoss = 0.688

func TestShortItems_ЛовитВыдумкуНаПлотномКадре(t *testing.T) {
	if !ShortItemsSuspicious(onigiriFake, onigiriFineLoss) {
		t.Errorf("детектор промолчал на сочинённом составе (позиций=%d, симв/поз=%.1f)",
			len(onigiriFake), CharsPerItem(onigiriFake))
	}
}

// Обратная сторона: на ПРАВДЕ детектор молчать обязан, иначе каждый верный разбор
// плотной этикетки уходил бы на вторую оплаченную эскалацию.
func TestShortItems_МолчитНаВерномРазборе(t *testing.T) {
	if ShortItemsSuspicious(onigiriTrue, onigiriFineLoss) {
		t.Errorf("детектор сработал на верном разборе (позиций=%d, симв/поз=%.1f)",
			len(onigiriTrue), CharsPerItem(onigiriTrue))
	}
}

// Ключевая защита от ложных срабатываний: короткие позиции сами по себе — норма.
// «мука, сахар, соль, дрожжи, вода, масло, яйцо, ваниль» — обычная этикетка печенья,
// и без признака плотного кадра её трогать нельзя.
func TestShortItems_НеСрабатываетНаЧистомКадре(t *testing.T) {
	plain := []string{"мука", "сахар", "соль", "дрожжи", "вода", "масло", "яйцо", "ванилин", "разрыхлитель"}
	if ShortItemsSuspicious(plain, 0.05) {
		t.Error("детектор сработал на обычной короткой этикетке при чистом кадре")
	}
	// А вот на плотном кадре та же форма уже подозрительна — там короткому списку
	// взяться неоткуда: в кадре много мелкого текста, который никуда не делся.
	if !ShortItemsSuspicious(plain, onigiriFineLoss) {
		t.Error("на плотном кадре короткий список должен считаться подозрительным")
	}
}

func TestShortItems_КороткийСписокНеТрогаем(t *testing.T) {
	// Меньше minSuspectItems: «молоко, закваска» — честный состав творога, и на
	// сколь угодно плотном кадре это не признак выдумки.
	short := []string{"молоко", "закваска"}
	if ShortItemsSuspicious(short, onigiriFineLoss) {
		t.Error("детектор сработал на списке из двух позиций")
	}
}

func TestCharsPerItem_СчитаетРуныНеБайты(t *testing.T) {
	// Кириллица в UTF-8 занимает два байта на символ: по байтам «сахар» дал бы 10,
	// и все пороги уехали бы вдвое.
	if got := CharsPerItem([]string{"сахар"}); got != 5 {
		t.Errorf("CharsPerItem = %v, ждали 5 (рун, а не байт)", got)
	}
	if got := CharsPerItem(nil); got != 0 {
		t.Errorf("CharsPerItem(nil) = %v, ждали 0", got)
	}
}

// Числа кейса — как утверждение, а не как комментарий: если правка формулы сблизит
// правду и выдумку, тест обязан упасть здесь, а не на проде.
func TestОнигириПравдаИВыдумкаРазличимыПоФорме(t *testing.T) {
	tr, fk := CharsPerItem(onigiriTrue), CharsPerItem(onigiriFake)
	if tr < 150 {
		t.Errorf("симв/позицию у правды = %.1f, ждали ~192", tr)
	}
	if fk > maxCharsPerItem {
		t.Errorf("симв/позицию у выдумки = %.1f, ждали ≤%d", fk, maxCharsPerItem)
	}
	t.Logf("правда %.1f симв/поз (%d позиций) против выдумки %.1f (%d позиций)",
		tr, len(onigiriTrue), fk, len(onigiriFake))
}
