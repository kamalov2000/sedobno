package pipeline

import (
	"math"

	"github.com/sostav/api/internal/llm"
)

// Единицы и согласованность калорийности с этикетки.
//
// На российских этикетках энергию печатают в ДВУХ единицах — «640 кДж / 153 ккал», —
// и модель регулярно берёт первое число. Промпт про это предупреждает (extract_v1.txt),
// но инструкция не гарантия: живой прогон 05.08.2026 дал kcal=640 при белках 16 и жирах
// 10, то есть кДж в поле ккал. Наружу это уезжало как «640 ккал/100 г», а дневник — он
// согласует ккал с макросами по Атуотеру (см. meal.reconcile) — сохранял те же данные
// как 154 ккал. Два соседних экрана показывали числа, различающиеся вчетверо.
//
// Здесь тот же приём, что в дневнике, плюс распознавание кДж по физической границе.
const (
	// kjPerKcal — множитель перевода: 1 ккал = 4.184 кДж.
	kjPerKcal = 4.184
	// scanKcalTolerance — допустимое расхождение kcal с 4Б+4У+9Ж, прежде чем пересчитать.
	// Тот же смысл и порядок, что kcalTolerance в meal: этикетки округляют, и требовать
	// точного совпадения нельзя.
	scanKcalTolerance = 0.30
)

// Причина правки — для лога и тестов (наружу не отдаётся).
const (
	fixNone    = ""
	fixKJ      = "kj_to_kcal" // число оказалось килоджоулями — перевели в ккал
	fixAtwater = "atwater"    // ккал не бьются с макросами — пересчитали из БЖУ
	fixDropped = "dropped"    // ни одна гипотеза не сходится — число убрано
)

// reconcileNutritionUnits чинит калорийность в пищевой ценности с этикетки и возвращает
// причину правки (fixNone — не трогали). Меняет n на месте.
//
// Опора — физический потолок: белки и жиры на этикетке заявлены ПОЛНОСТЬЮ, поэтому весь
// остаток массы в самом калорийном случае — углеводы (4 ккал/г). Больше этого потолка
// «ккал» быть не может ни у одного продукта, и число, его пробившее, — это кДж.
// Потому и требуются оба макроса: без них потолок не построить, и молча делить на 4.184
// по одному лишь «больно большому» значению — гадание.
func reconcileNutritionUnits(n *llm.Nutrition) string {
	if n == nil || n.Kcal == nil || *n.Kcal <= 0 {
		return fixNone
	}
	// Границу строим на 100 г/мл — на других базах (порция, упаковка) она бессмысленна.
	// Пустой basis трактуем как «не знаем» и в проверку потолка не идём.
	per100 := n.Basis == "100g" || n.Basis == "100ml"
	p, f, c := n.ProteinG, n.FatG, n.CarbG
	kcal := *n.Kcal

	// Полные макросы — можно посчитать ожидаемую калорийность по Атуотеру.
	full := p != nil && f != nil && c != nil
	computed := 0.0
	if full {
		computed = 4*(*p) + 4*(*c) + 9*(*f)
	}

	if per100 && p != nil && f != nil {
		ceiling := 4*(*p) + 9*(*f) + 4*math.Max(0, 100-*p-*f)
		if ceiling > 0 && kcal > ceiling {
			// Гипотеза «это килоджоули»: после перевода число обязано влезть под потолок
			// и (если макросы полные) сойтись с Атуотером.
			if asKcal := kcal / kjPerKcal; asKcal <= ceiling && (!full || agrees(asKcal, computed)) {
				*n.Kcal = round1(asKcal)
				return fixKJ
			}
			// Не кДж и физически невозможно. Есть полные макросы — верим им; нет —
			// убираем число совсем: показать заведомо неверную калорийность хуже, чем
			// не показать никакой (карточка КБЖУ переживает отсутствие kcal).
			if full && computed > 0 {
				*n.Kcal = round1(computed)
				return fixAtwater
			}
			n.Kcal = nil
			return fixDropped
		}
	}

	// Под потолком — обычное согласование с макросами, ровно как в дневнике.
	if full && computed > 0 && !agrees(kcal, computed) {
		*n.Kcal = round1(computed)
		return fixAtwater
	}
	return fixNone
}

// agrees — расхождение в пределах допуска.
func agrees(kcal, computed float64) bool {
	if computed <= 0 {
		return false
	}
	return math.Abs(kcal-computed)/computed <= scanKcalTolerance
}

func round1(v float64) float64 { return math.Round(v*10) / 10 }
