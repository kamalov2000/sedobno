package server

import "math"

// Оценка часового пояса пользователя по его же меткам приёмов.
//
// Часовых поясов мы не спрашиваем (в профиле только рост/вес/цель), но вечерний итог
// нельзя слать по единому московскому времени: 21:00 МСК — это 04:00 во Владивостоке,
// а ночной пуш означает блокировку бота. Зато у нас есть время, когда человек РЕАЛЬНО
// записывает еду, и по нему пояс восстанавливается с точностью, которой хватает: задача
// не «попасть в 21:00», а «не попасть в ночь».
//
// Часы — величина ЦИКЛИЧЕСКАЯ, и обычная медиана на них врёт. Владивосток (UTC+10) с
// приёмами в 9, 14 и 20 локальных даёт UTC-часы 23, 4, 10: наивная медиана — 10, отсюда
// offset +4 и итог в 6 утра. Поэтому усредняем векторно (круговое среднее): каждый час —
// точка на окружности, складываем и берём угол суммы. Для того же примера получается
// ≈4.3 и offset +10 — верно.
const (
	// digestAnchorHour — какому ЛОКАЛЬНОМУ часу соответствует типичная середина
	// пищевого дня. Завтрак/обед/ужин дают центр масс около раннего вечера; 14 —
	// эмпирическая точка отсчёта, от которой пляшет вся оценка.
	digestAnchorHour = 14.0
	// Границы правдоподобия: РФ живёт в UTC+2…UTC+12. Оценка вне диапазона означает,
	// что данных мало или они шумные, — тогда честнее московское время, чем экзотика.
	minOffsetHours = 2
	maxOffsetHours = 12
	// mskOffsetHours — фолбэк, когда оценивать не по чему.
	mskOffsetHours = 3
	// minSamplesForOffset — меньше этого числа приёмов оценке верить нельзя: один
	// ночной перекус утащил бы человека на другой конец страны.
	minSamplesForOffset = 5
)

// guessUTCOffset оценивает смещение часового пояса (в часах) по UTC-часам приёмов.
// hours — часы (0..23) момента, когда пользователь записывал еду. Мало данных или
// вырожденный разброс — московские +3.
func guessUTCOffset(hours []int) int {
	if len(hours) < minSamplesForOffset {
		return mskOffsetHours
	}
	var sumSin, sumCos float64
	for _, h := range hours {
		a := 2 * math.Pi * float64(h) / 24
		sumSin += math.Sin(a)
		sumCos += math.Cos(a)
	}
	// Вырожденный случай: точки равномерно по кругу — направления нет, угол не определён.
	if math.Hypot(sumSin, sumCos) < 1e-9 {
		return mskOffsetHours
	}
	mean := math.Atan2(sumSin/float64(len(hours)), sumCos/float64(len(hours))) / (2 * math.Pi) * 24
	if mean < 0 {
		mean += 24
	}
	// Локальный якорь минус средний час в UTC и есть искомое смещение.
	off := int(math.Round(digestAnchorHour - mean))
	// Нормализуем в один оборот, прежде чем судить о правдоподобии: -14 и +10 — это
	// одно и то же смещение, и отбрасывать второе из-за записи первым было бы ошибкой.
	for off < 0 {
		off += 24
	}
	for off >= 24 {
		off -= 24
	}
	if off < minOffsetHours || off > maxOffsetHours {
		return mskOffsetHours
	}
	return off
}
