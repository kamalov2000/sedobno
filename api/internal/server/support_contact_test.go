package server

import (
	"strings"
	"testing"
)

// Человек, который только что написал, — самый вовлечённый, какой у нас бывает. Замер
// 06.09: из четверых написавших двое к моменту ответа уже перестали пользоваться
// продуктом (один — за две минуты до собственного обращения). Поэтому контакт владельца
// отдаём сразу, а не оставляем человека с «передал разработчику» и без продолжения.
func TestSupportThanks_ОтдаётКонтакт(t *testing.T) {
	txt := supportThanks("@kamalovTG")
	if !strings.Contains(txt, "@kamalovTG") {
		t.Fatalf("в ответе нет контакта:\n%s", txt)
	}
	// Тупиковой формулировки «передал разработчику» без продолжения быть не должно:
	// именно она оставляла человека без способа ответить.
	if !strings.Contains(txt, "пишите ему напрямую") {
		t.Errorf("нет приглашения написать лично:\n%s", txt)
	}
}

// Контакт не задан — поведение ровно прежнее. Это дефолт для установки без
// SUPPORT_CONTACT, и менять его молча нельзя.
func TestSupportThanks_БезКонтактаПрежнийТекст(t *testing.T) {
	txt := supportThanks("")
	if txt != "Спасибо, передал разработчику 🙌" {
		t.Errorf("текст без контакта изменился: %q", txt)
	}
	if strings.Contains(txt, "@") {
		t.Errorf("в тексте без контакта появился @: %q", txt)
	}
}
