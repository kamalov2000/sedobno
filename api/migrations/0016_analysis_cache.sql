-- Кэш разбора по хэшу изображения. Причина — живой кейс тестера 27.07 (beta-сканы
-- 52/53/54): ОДНО фото онигири, три прогона, три разных вердикта — 81, 38, 68. Для
-- человека это не «погрешность модели», а «программа врёт»: он видит своими глазами,
-- что фото одно и то же. Пока один и тот же файл может дать разный ответ, доверять
-- продукту нельзя, сколько бы ни был хорош средний случай.
--
-- Кэш чинит ровно это: тот же файл → тот же ответ, мгновенно и без списания квоты.
-- ВАЖНО, чего он НЕ чинит: он замораживает ПЕРВЫЙ ответ, а первым в том кейсе был
-- как раз галлюцинированный (81). Стабильность — не то же самое, что правильность;
-- за правильность отвечает антигаллюцинационный гейт и эскалация (pipeline).
--
-- Ключ — (user_id, kind, image_sha). Кэш НАМЕРЕННО пер-юзерный, а не глобальный:
--   • фото еды — личные (тарелка в кадре кухни), отдавать чужой разбор нельзя;
--   • глобальный кэш позволял бы проверять «а сканировал ли кто-то этот файл»;
--   • ошибочный разбор одного пользователя не расползается на всех.
-- Плата за это — не экономим на одинаковых фото РАЗНЫХ людей; для беты неактуально.
CREATE TABLE analysis_cache (
    id          BIGSERIAL   PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    -- kind: 'scan' (сканер составов) | 'meal' (счётчик калорий). Пайплайны разные,
    -- ответы несовместимы — один и тот же файл в двух сканерах даёт две записи.
    kind        TEXT        NOT NULL,
    -- image_sha: sha256 НОРМАЛИЗОВАННЫХ кадров (после imaging.Normalize), hex.
    -- Именно нормализованных, а не исходных: в модель уходят они, и ключ обязан
    -- совпадать с тем, что реально видела модель. Мультикадр — один хэш на набор.
    image_sha   TEXT        NOT NULL,
    -- result: сериализованный результат пайплайна, из которого собирается ответ
    -- клиенту. Не сам HTTP-ответ: scans_left/scan_number зависят от текущего
    -- состояния пользователя и подставляются заново на каждом попадании.
    result      JSONB       NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    hit_count   INTEGER     NOT NULL DEFAULT 0,
    last_hit_at TIMESTAMPTZ
);

CREATE UNIQUE INDEX analysis_cache_key ON analysis_cache (user_id, kind, image_sha);
-- Индекс под чистку по TTL (90 дней): подметание идёт по created_at.
CREATE INDEX analysis_cache_created ON analysis_cache (created_at);

