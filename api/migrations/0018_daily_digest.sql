-- Вечерний итог дня (ретеншн, п.3): единственная механика, которая сама зовёт человека
-- обратно. Шлём ТОЛЬКО тем, у кого в этот день есть запись в дневнике — итог дня без
-- записей подводить не из чего, а рассылка неактивным читается как понукание.
--
-- Два поля:
--   daily_digest_enabled — тумблер в профиле и /stop_daily (алиас — «стоп» текстом).
--     Умолчание true: механика по определению приходит только тем, кто уже ведёт
--     дневник, и первое же сообщение объясняет, как её выключить.
--   last_digest_date — ЛОКАЛЬНАЯ дата последнего отправленного итога (не timestamp):
--     защита от повторов должна работать в календаре пользователя. Воркер тикает чаще,
--     чем раз в сутки, и без этой отметки один вечер давал бы несколько сообщений.
--     Дата, а не отметка времени, — потому что вопрос ровно один: «за этот день уже
--     отправляли?», и сравнение дат отвечает на него без арифметики часовых поясов.
ALTER TABLE users
    ADD COLUMN daily_digest_enabled BOOLEAN NOT NULL DEFAULT true,
    ADD COLUMN last_digest_date     DATE;

-- Частичный индекс: воркер каждые полчаса ищет кандидатов среди включивших итог, а это
-- меньшинство строк по мере отписок. Полный индекс по флагу здесь бесполезен.
CREATE INDEX idx_users_digest ON users (last_digest_date) WHERE daily_digest_enabled;

