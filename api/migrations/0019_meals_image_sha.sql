-- Кадр, из которого получен приём: sha256 НОРМАЛИЗОВАННЫХ изображений — тот же ключ,
-- по которому живёт кэш разбора (analysis_cache.image_sha).
--
-- Зачем колонка. Повторно присланное фото попадает в кэш: модель не вызывается, квота
-- не списывается (платить не за что) — но приём в дневник до сих пор создавался каждый
-- раз заново. 17.08.2026 один и тот же кадр дал ПЯТЬ одинаковых приёмов за день, и
-- пользователь читал это как сломанный счётчик: разборов пять, а остаток не двигается.
-- Чтобы показать существующий приём вместо шестого дубля, его надо уметь найти — по
-- паре (кто, какой кадр) в пределах дня.
--
-- NULL — приём не из фото (руками/словами/из скана) либо создан до этой миграции.
-- Уникальности здесь НЕТ намеренно: тот же кадр ЗАВТРА — законный новый приём (вчерашний
-- салат съеден снова), и дубль внутри дня решается запросом, а не constraint'ом, потому
-- что «день» у нас клиентский (local_date), а не свойство строки.
ALTER TABLE meals ADD COLUMN image_sha TEXT NULL;

-- Поиск дубля за день: (пользователь, кадр, день). Частичный — у ручных приёмов sha нет,
-- и держать их в индексе незачем.
CREATE INDEX idx_meals_user_sha_day ON meals (user_id, image_sha, local_date)
    WHERE image_sha IS NOT NULL;

