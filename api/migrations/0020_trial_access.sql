-- +goose Up
-- Переход с «10 сканов + 10 разборов навсегда» на НЕДЕЛЮ полного доступа.
--
-- Прежняя модель мерила щедрость штуками и не имела срока: человек мог растянуть свои
-- 10 разборов на полгода, так и не поняв, зачем платить, — а продукт продаётся привычкой,
-- которая складывается за неделю ежедневных записей, а не за 10 разрозненных проб.
--
-- Триал ограничен И сроком, И потолком: 7 дней, но не больше trialMealLimit разборов и
-- trialScanLimit сканов (см. internal/server/access.go). Потолок — не жадность, а защита
-- от фарма: обычному человеку 30 приёмов за неделю хватает с запасом (это 4 в день).
--
-- ВАЖНО, что триал НЕ закрывает: дневник, историю, вес, воду и уже сохранённые разборы.
-- Стена встаёт только перед СОЗДАНИЕМ нового разбора или скана. Забирать у человека его
-- собственные записи нельзя — он их и накопил ради того, чтобы к ним возвращаться.

-- Конец триала. DEFAULT считается на вставке, а строка пользователя создаётся при первом
-- касании бота (/start) или первом входе в mini-app — то есть срок идёт ровно от первого
-- касания, отдельная колонка «начало» для этого не нужна (есть created_at).
ALTER TABLE users ADD COLUMN trial_expires_at TIMESTAMPTZ NOT NULL DEFAULT (now() + interval '7 days');

-- Когда ушло напоминание за сутки до конца. NULL — ещё не уходило. Ровно это поле и
-- держит обещание «одно сообщение, не серия»: рассыльщик берёт только строки с NULL.
ALTER TABLE users ADD COLUMN trial_reminder_sent_at TIMESTAMPTZ NULL;

-- Выборка кандидатов на напоминание идёт по сроку среди неподписчиков.
CREATE INDEX idx_users_trial_expires ON users (trial_expires_at) WHERE is_subscribed = false;

-- Уже существующие пользователи. Двух моделей одновременно не держим: всем неделя от
-- момента наката, старые счётчики в ноль. Кто успел потратить 10 сканов по прежней
-- модели, получает полноценную неделю, а не огрызок, — это осознанная плата за смену
-- правил в одностороннем порядке.
--
-- DEFAULT выше существующим строкам уже проставил now()+7 дней на момент ALTER, но
-- полагаться на это не будем: пишем явно, чтобы намерение читалось из миграции.
UPDATE users SET
    trial_expires_at = now() + interval '7 days',
    free_meals_used = 0,
    free_scans_used = 0;

