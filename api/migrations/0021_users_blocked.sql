-- +goose Up
-- Отметка «пользователь заблокировал бота».
--
-- Зачем колонка, а не вывод из логов. 08.09 выяснилось, что 18 человек из 78 пришедших с
-- размещения заблокировали бота. Узнали мы об этом СЛУЧАЙНО — по 403 в логе при попытке
-- отправить напоминание, — и ровно два раза это стоило нам неверных выводов:
--
--   1) рассыльщики ставят пометку об отправке ТОЛЬКО после успеха, поэтому заблокировавший
--      оставался в выборке навсегда: одному и тому же человеку напоминание пытались
--      отправить каждый час, шесть раз подряд, до конца его триала;
--   2) эти 18 сидят в знаменателе каждой воронки. «87% не сделали ни одного кадра»
--      складывается из молчаливого отвала и активного отвержения, а это разные вещи с
--      разными причинами — считать их одним числом значит мерить среднее по палате.
--
-- NULL — не заблокирован (подавляющее большинство). Отметка ставится при первой же
-- окончательной ошибке 403 от Bot API и снимается, если человек снова заходит в приложение
-- (разблокировал — значит опять наш).
ALTER TABLE users ADD COLUMN blocked_at TIMESTAMPTZ NULL;

-- Частичный: интересуют только заблокировавшие, их единицы процентов.
CREATE INDEX idx_users_blocked ON users (blocked_at) WHERE blocked_at IS NOT NULL;

-- +goose Down
DROP INDEX IF EXISTS idx_users_blocked;
ALTER TABLE users DROP COLUMN IF EXISTS blocked_at;
