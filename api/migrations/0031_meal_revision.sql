-- Защита версии приёма (решение владельца 13.10.2026, backlog п.18). Правка присылает номер
-- версии, которую видела; устаревшая правка отклоняется, а не перезаписывает более новую.
--
-- revision — номер версии записи: растёт на каждой правке. Существующим записям:
-- никогда не правленные — 1, правленные (edited) — 2. Это важно для СТАРОГО клиента без
-- поля revision: сервер пускает его правку только на версию 1 (запись ни разу не меняли —
-- его основа заведомо актуальна). Уже правленную запись старый клиент перезаписать не может.
ALTER TABLE meals
    ADD COLUMN revision INTEGER NOT NULL DEFAULT 1,
    -- Ключ последней применённой правки: повтор той же правки после потерянного ответа
    -- узнаётся по нему и отвечает успехом, а не «версия устарела».
    ADD COLUMN last_edit_key TEXT;

UPDATE meals SET revision = 2 WHERE edited;

