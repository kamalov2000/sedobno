import { describe, it, expect } from "vitest";
// ?raw отдаёт исходник строкой средствами vite — без node:fs и @types/node в проекте.
import src from "./App.tsx?raw";

// Регрессия на дубль экрана «Подписка» (03.08.2026): блок
//   {view === "subscription" && me && (<SubscriptionScreen … />)}
// оказался в App.tsx ДВАЖДЫ подряд — copy-paste при мерже подписок v2 (807adb1).
// Оба блока проходили по одному и тому же условию, поэтому экран рисовался в два
// одинаковых слоя. Это НЕ двойной монтаж и не гонка перечитывания /me: дубль
// детерминированный, на любом пути входа.
//
// Ловим это на уровне исходника, а не рендера, намеренно. Рендерный тест поймал бы
// только тот экран, который ему написали, — а ошибка тут копипастная и заводится
// в любом из двух десятков блоков. Проверка «у каждого view ровно один блок
// отрисовки» покрывает их все и стоит одного чтения файла.

describe("App: блоки отрисовки экранов", () => {
  it("на каждый view приходится ровно один блок {view === \"…\" && (", () => {
    // Считаем только НАЧАЛА блоков отрисовки — `{view === "x" &&`. Условия внутри
    // логики (isOutcome/isList и прочие `const … = view === "x" || …`) идут без
    // открывающей фигурной скобки и сюда не попадают.
    const sites = [...src.matchAll(/\{view === "([a-z_]+)" &&/g)].map((m) => m[1]);
    expect(sites.length).toBeGreaterThan(10); // регэксп не разъехался с файлом

    const seen = new Map<string, number>();
    for (const v of sites) seen.set(v, (seen.get(v) ?? 0) + 1);
    const duplicated = [...seen.entries()].filter(([, n]) => n > 1);

    expect(duplicated, `экран(ы) с несколькими блоками отрисовки: ${duplicated.map(([v, n]) => `${v}×${n}`).join(", ")}`).toEqual([]);
  });
});
